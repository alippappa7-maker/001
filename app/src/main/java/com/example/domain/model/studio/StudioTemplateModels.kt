package com.example.domain.model.studio

/**
 * أنواع القوالب الجاهزة لمحرك التركيب. كل قالب يحاكي أسلوبًا بصريًا معروفًا
 * (تسلسل مشاهد + ألوان + تحريك) دون أن يختلق أي نص ديني — النصوص كلها
 * تأتي من إدخال المستخدم عبر [TadhkirahTemplateInput] أو من [VideoProject].
 */
enum class StudioTemplateType {
    /** المسار العام الحالي: يبني المشاهد من VideoProject.plan.scenes مباشرة. */
    DEFAULT,

    /**
     * قالب "تذكرة وموعظة": يحاكي أسلوب فيديوهات التذكير الدعوية —
     * بطاقة آية مزخرفة، ثم أسئلة تأملية متوهجة على خلفيات داكنة متدرجة،
     * ثم كلمة تأثيرية، ثم خاتمة بشعار العلامة.
     */
    TADHKIRAH_MAWIDHA,

    /**
     * قالب "النعيم والزهد": يحاكي أسلوب الفيديوهات التأملية الهادئة —
     * خلفيات دافئة ذهبية/كهرمانية (غروب إجرائي عبر Canvas)، نص حديث/أثر
     * كبير يتلاشى بهدوء، مشاهد قليلة الحركة.
     */
    NAEEM_ZUHD,

    /**
     * قالب "اقتباسات متحركة": خلفية داكنة موحّدة، اقتباسات/مواعظ قصيرة
     * متتابعة تظهر بتوهج وتلاشٍ، مناسب لأي نص قصير يُدخله المستخدم.
     */
    MOVING_QUOTES
}

/**
 * مدخلات قالب "النعيم والزهد". كل نص من المستخدم فقط — لا حديث أو أثر
 * افتراضي مضمّن؛ الحقول الفارغة تُستبدل بـ placeholder واضح.
 */
data class NaeemZuhdTemplateInput(
    /** نص الحديث/الأثر الرئيسي الذي يظهر بخط كبير على الخلفية الذهبية. يُدخله المستخدم. */
    val hadithText: String = "",
    /** مصدر الحديث/الأثر (مثل: رواه البخاري) — اختياري، يظهر بخط أصغر تحت النص. */
    val hadithSource: String = "",
    /** جمل تأملية إضافية قصيرة تُعرض في مشاهد متتابعة (اختيارية). */
    val reflectiveLines: List<String> = emptyList(),
    /** اسم العلامة/الجهة الذي يظهر في الخاتمة. */
    val brandName: String = "قبس"
)

/**
 * مدخلات قالب "اقتباسات متحركة". كل اقتباس نص من المستخدم فقط.
 */
data class MovingQuotesTemplateInput(
    /** قائمة الاقتباسات/المواعظ القصيرة — كل عنصر يصبح مشهدًا مستقلًا. يجب ألا تكون فارغة. */
    val quotes: List<String> = emptyList(),
    /** اسم العلامة/الجهة الذي يظهر في الخاتمة. */
    val brandName: String = "قبس"
)

/**
 * مدخلات قالب "تذكرة وموعظة". كل حقل نصي يُملأ من المستخدم فقط؛ لا نص ديني
 * افتراضي مضمّن في الكود — إن تُرك [openingVerseText] فارغًا يُستخدم placeholder
 * واضح يطلب من المستخدم إدخال الآية بنفسه.
 */
data class TadhkirahTemplateInput(
    /** نص الآية/الاقتباس الافتتاحي الذي يظهر داخل البطاقة المزخرفة. يُدخله المستخدم. */
    val openingVerseText: String = "",
    /** عبارات تأملية متتابعة تظهر كأسئلة/جمل متوهجة (مشاهد الوسط). */
    val reflectiveLines: List<String> = emptyList(),
    /** كلمة أو جملة قصيرة مؤثرة تُعرض بخط كبير جدًا في مشهد منفرد. */
    val impactWord: String = "",
    /** جملتا الخاتمة (تُعرضان فوق خلفية ليلية بديلة). */
    val closingLines: List<String> = emptyList(),
    /** اسم العلامة/الجهة الذي يظهر كنص بسيط في الزاوية العلوية — ليس شعار جهة أخرى. */
    val brandName: String = "قبس"
)
